// instanceof 

/* 

PHP-তে আমরা check করতে পারি কোনো Object কোন Class-এর instance কিনা।

# For Example:

class User {}

$user = new User();

var_dump($user instanceof User); // output: bool(true)

# Another Example:

class Admin {}

var_dump($user instanceof Admin);  // output: bool(false)

*/